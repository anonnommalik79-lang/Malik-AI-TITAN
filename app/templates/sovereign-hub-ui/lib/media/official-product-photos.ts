export function normalizeIPhoneSubject(input: string): string {
  return input.replace(/(?:айфон[а-я]*|iphone)/giu, "iPhone")
    .replace(/iPhone\s+17\s+Air/giu, "iPhone Air")
    .replace(/iPhone\s*(?:2G|первое\s+поколение|original)/giu, "iPhone")
    .replace(/\(\s*([123])(?:-?[еe])?\s*(?:поколени[ея]|generation)\s*\)/giu, "($1 generation)")
    .replace(/([123])(?:st|nd|rd) generation/giu, "$1 generation")
    .replace(/\s+/gu, " ").trim()
}

export function officialIPhonePhoto(subject: string): { title: string; url: string } | null {
  const label = normalizeIPhoneSubject(subject).toLowerCase()
  const entry = Object.entries(APPLE_IPHONE_PHOTOS).find(([title]) => normalizeIPhoneSubject(title).toLowerCase() === label)
  return entry ? { title: entry[0], url: entry[1] } : null
}

/** Named models only: preserve the list in the answer without inventing variants. */
export function namedIPhoneSubjects(text: string): string[] {
  const pattern = /(?:iphone|айфон[а-я]*)\s*(?:(?:1[0-9]|[3-9])(?:e|s|c|gs|g)?(?:\s+(?:pro\s+max|pro|plus|mini|air))?|xs(?:\s+max)?|xr|x|air|se(?:\s*\(\s*[123](?:st|nd|rd|-?[еe])?\s*(?:поколени[ея]|generation)\s*\))?|2g)(?![\p{L}\p{N}])/giu
  const subjects = [...text.matchAll(pattern)].map((match) => normalizeIPhoneSubject(match[0]))
  if (/(?:iphone|айфон[а-я]*)\s*\(\s*(?:первое|first|2g)/iu.test(text)) subjects.unshift("iPhone")
  return [...new Set(subjects.map((title) => officialIPhonePhoto(title)?.title || title))].slice(0, 60)
}

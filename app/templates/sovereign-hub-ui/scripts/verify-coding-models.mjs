import assert from "node:assert/strict"
import fs from "node:fs"

/**
 * The website builder was falling through to its generic local template on
 * every request, and the reason was not the planner - it was three dead model
 * ids underneath it.
 *
 * For code, debug and project the router asked Cerebras for "zai-glm-4.7", a
 * Z.AI model Cerebras does not serve; Gemini for "gemini-1.5-pro", retired from
 * the API; and Groq for "llama-3.1-70b-versatile", decommissioned. Cerebras led
 * the order for every building task, so the chain was: fail, fail, then a
 * handful of providers with no keys, then the template. Every generated site
 * came out the same because none of them were generated by a model at all.
 *
 * These assertions are about names that go stale, so they are written to fail
 * loudly rather than to be clever.
 */

function codeOf(file) {
  // Line-start comments only: matching "/*" anywhere also matches it inside a
  // string, and the fake comment then eats real code before it is asserted on.
  return fs.readFileSync(file, "utf8")
    .replace(/^[ \t]*\/\*[\s\S]*?\*\//gm, "")
    .replace(/^[ \t]*\/\/.*$/gm, "")
}

let failures = 0
function check(name, fn) {
  try {
    fn()
    console.log(`  ok  ${name}`)
  } catch (error) {
    failures += 1
    console.error(`  FAIL ${name}\n       ${error.message.split("\n")[0]}`)
  }
}

const models = codeOf("lib/ai/models.ts")
const providers = codeOf("lib/ai/providers.ts")
const gemini = codeOf("lib/ai/providers/gemini.ts")

console.log("\nmodels the providers actually serve")

check("no provider is asked for a model that was retired or belongs elsewhere", () => {
  for (const dead of ["gemini-1.5-pro", "zai-glm-4.7", "llama-3.1-70b-versatile"]) {
    assert.ok(!models.includes(dead), `"${dead}" is dead and must not be a default`)
  }
})

check("Cerebras is asked for the model its own health check reports", () => {
  assert.match(models, /CEREBRAS_CODE_MODEL \|\| "gpt-oss-120b"/,
    "code, debug and project must use the model Cerebras actually runs")
})

check("Groq is asked for a model this repo has already proven works", () => {
  // The Voice router calls Groq with gpt-oss and gets answers, so it is the one
  // model id in this codebase with evidence behind it.
  assert.match(models, /GROQ_MODEL \|\| "openai\/gpt-oss-20b"/)
})

check("Codestral is wired in as a real provider", () => {
  assert.match(models, /MISTRAL_CODE_MODEL \|\| "codestral-latest"/, "a coding model, not a chat model asked nicely")
  assert.match(providers, /mistralProvider/, "the provider must be registered")
  assert.ok(fs.existsSync("lib/ai/providers/mistral.ts"), "the provider file must exist")
})

console.log("\nwho gets asked first")

check("everything that builds leads with Gemini, then Codestral", () => {
  const order = providers.match(/const ROUTING_ORDER[\s\S]*?\n\}/)?.[0] || ""
  for (const task of ["code", "debug", "project"]) {
    const line = order.match(new RegExp(`${task}: \\[([^\\]]*)\\]`))?.[1] || ""
    const ids = line.split(",").map((value) => value.trim().replace(/"/g, ""))
    assert.equal(ids[0], "gemini", `${task} must lead with Gemini`)
    assert.equal(ids[1], "mistral", `${task} must fall to Codestral second`)
  }
})

check("Cerebras is still in the chain, just not leading it", () => {
  const order = providers.match(/const ROUTING_ORDER[\s\S]*?\n\}/)?.[0] || ""
  const project = order.match(/project: \[([^\]]*)\]/)?.[1] || ""
  assert.ok(project.includes("cerebras"), "it is fast and configured, it stays as a fallback")
  assert.ok(!/project: \["cerebras"/.test(order), "but it must not be first any more")
})

console.log("\nsurviving the next rename")

check("Gemini tries a list of model ids instead of one hardcoded name", () => {
  assert.match(gemini, /GEMINI_CANDIDATES/, "one stale id must not take the provider down again")
  assert.match(gemini, /workingGeminiModel/, "and the one that answers should be remembered")
})

check("only a missing model advances to the next candidate", () => {
  // A rejected key or a spent quota fails identically on every candidate;
  // walking the whole list would multiply one failure into several.
  assert.match(gemini, /function modelMissing/)
  assert.match(gemini, /modelMissing\(response\.status, lastError\)/)
})

check("an explicit model from the environment still wins outright", () => {
  assert.match(gemini, /GEMINI_CODE_MODEL\?\.trim\(\)/)
  assert.match(gemini, /if \(explicit\) return \[explicit\]/)
})

console.log(failures ? `\n${failures} failing\n` : "\nall coding model checks passed\n")
process.exit(failures ? 1 : 0)
